function inside(shape: Shape, x: number, y: number): boolean {
  const dx = Math.abs(x - (CREST_W - 1) / 2);
  switch (shape) {
    case 'heater': {
      if (y < 2) return dx <= 12 + y;
      if (y < 17) return true;
      return dx <= 13.5 * (1 - ((y - 17) / 14.5) ** 1.7);
    }
    case 'round': return dx * dx + (y - 15.5) ** 2 <= 14.2 ** 2;
    case 'hex': return dx <= Math.min(13.5, 5.5 + y * 1.5, 5.5 + (CREST_H - 1 - y) * 1.5);
    case 'crown': {
      if (y < 3) return dx <= 2 || (dx >= 5 && dx <= 7) || dx >= 10.5;
      if (y < 21) return true;
      return dx <= 13.5 * (1 - ((y - 21) / 10.5) ** 2.2) + 0.5;
    }
  }
}

/** How many pixels in from the crest's edge each cell is. 0 is outside. */
function depths(shape: Shape): number[][] {
  const grid: number[][] = [];
  for (let y = 0; y < CREST_H; y++) {
    const row: number[] = [];
    for (let x = 0; x < CREST_W; x++) row.push(inside(shape, x, y) ? 9 : 0);
    grid.push(row);
  }
  const at = (x: number, y: number) => grid[y]?.[x] ?? 0;
  for (let d = 1; d <= 4; d++) {
    const edge: [number, number][] = [];
    for (let y = 0; y < CREST_H; y++) for (let x = 0; x < CREST_W; x++) {
      if (at(x, y) === 9 && (at(x - 1, y) < d || at(x + 1, y) < d || at(x, y - 1) < d || at(x, y + 1) < d)) edge.push([x, y]);
    }
    for (const [x, y] of edge) grid[y]![x] = d;
  }
  return grid;
}

const mix = (a: string, b: string, k: number): string => {
  const p = (s: string, i: number) => parseInt(s.slice(i, i + 2), 16);
  const ch = (i: number) => Math.round(p(a, i) + (p(b, i) - p(a, i)) * k).toString(16).padStart(2, '0');
  return `#${ch(1)}${ch(3)}${ch(5)}`;
};

const OUTLINE = '#0a0e24';
const DARK = '#14181c';
const WHITE = '#f4f4ee';

/** The colours a team's crest uses. Near-black or too-close colours fall back so the art still shows. */
export function crestColors(t: Team) {
  const body = lum(t.primary) < 0.08 ? mix(t.primary, WHITE, 0.12) : t.primary;
  const main = lum(body) > 0.62 ? DARK : WHITE;
  const trim = lum(t.secondary) >= 0.2 ? t.secondary : main === WHITE ? WHITE : shade(body, 0.55);
  const accent = Math.abs(lum(t.secondary) - lum(body)) < 0.15 ? shade(main, main === WHITE ? 0.72 : 1.8) : t.secondary;
  return { body, main, trim, accent };
}

function bounds(art: string[]): { top: number; left: number; h: number; w: number } {
  const lit = art.map((r) => /[^.]/.test(r));
  const top = lit.indexOf(true);
  const bottom = lit.lastIndexOf(true);
  const cols = art.flatMap((r) => [...r].flatMap((ch, x) => (ch === '.' ? [] : [x])));
  const left = Math.min(...cols);
  return { top, left, h: bottom - top + 1, w: Math.max(...cols) - left + 1 };
}

function paint(ctx: CanvasRenderingContext2D, x: number, y: number, color: string): void {
  ctx.fillStyle = color;
  ctx.fillRect(x, y, 1, 1);
}

const urls = new Map<string, string>();

/** The crest as an image address, drawn once per team. Show it with `image-rendering: pixelated`. */
export function crestURL(id: string): string {
  const cached = urls.get(id);
  if (cached) return cached;
  const team = TEAM_BY_ID[id];
  const crest = CRESTS[id];
  if (!team || !crest) return '';
  const canvas = document.createElement('canvas');
  canvas.width = CREST_W;
  canvas.height = CREST_H;
  const ctx = canvas.getContext('2d')!;
  const col = crestColors(team);
  const grid = depths(crest.shape);
  for (let y = 0; y < CREST_H; y++) for (let x = 0; x < CREST_W; x++) {
    const d = grid[y]![x]!;
    if (d === 0) continue;
    if (d === 1) paint(ctx, x, y, OUTLINE);
    else if (d <= 3) paint(ctx, x, y, col.trim);
    else if (d === 4) paint(ctx, x, y, shade(col.body, 0.62));
    else paint(ctx, x, y, x < CREST_W / 2 ? col.body : shade(col.body, 0.84));
  }
  const inks: Record<string, string> = {
    '#': col.main, o: shade(col.main, col.main === WHITE ? 0.76 : 1.6), '+': col.accent, l: mix(col.accent, WHITE, 0.45), k: DARK, w: WHITE,
  };
  const b = bounds(crest.art);
  // The heater's point and the crown's merlons shift the crest's visual middle, so its emblem sits to match.
  const nudge = crest.shape === 'heater' ? -2 : crest.shape === 'crown' ? 1 : 0;
  const ox = Math.round((CREST_W - b.w) / 2) - b.left;
  const oy = Math.round((CREST_H - b.h) / 2) - b.top + nudge;
  crest.art.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.') paint(ctx, ox + x, oy + y, inks[ch]!); }));
  const url = canvas.toDataURL();
  urls.set(id, url);
  return url;
}

/** Overall strength as stars, from half a star to five, in half steps. */
export function starRating(off: number, def: number): number {
  const stars = (((off + def) / 2 - 60) / 37) * 4.5 + 0.5;
  return Math.max(0.5, Math.min(5, Math.round(stars * 2) / 2));
}

const STAR = ['....#....', '...###...', '...###...', '#########', '.#######.', '..#####..', '.###.###.', '.##...##.'];
const STAR_W = 9;
const STAR_GAP = 1;
const starUrls = new Map<number, string>();

/** Five stars as an image address, filled to the given rating. */
export function starsURL(rating: number): string {
  const cached = starUrls.get(rating);
  if (cached) return cached;
  const canvas = document.createElement('canvas');
  canvas.width = 5 * STAR_W + 4 * STAR_GAP;
  canvas.height = STAR.length;
  const ctx = canvas.getContext('2d')!;
  for (let s = 0; s < 5; s++) {
    STAR.forEach((row, y) => [...row].forEach((ch, x) => {
      if (ch !== '#') return;
      const lit = s + (x < 4 ? 0.5 : x === 4 ? 0.75 : 1) <= rating + 0.25;
      paint(ctx, s * (STAR_W + STAR_GAP) + x, y, lit ? '#ffd23f' : '#33458f');
    }));
  }
  const url = canvas.toDataURL();
  starUrls.set(rating, url);
  return url;
}
